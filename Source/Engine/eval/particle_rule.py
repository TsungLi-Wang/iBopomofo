def load_words(data_txt=DATA_TXT):
    """詞庫裡所有兩字詞。用來擋「便當／方法／動作／冷氣」這種
    「第一個字剛好是形容詞、但整個詞是名詞」的誤判。"""
    out = set()
    with open(data_txt, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#"):
                continue
            p = line.split()
            if len(p) >= 2 and len(p[1]) == 2:
                out.add(p[1])
    return out


def load_verbs(data_txt=DATA_TXT):
    """可以接補語的字 = 詞庫收錄的「X得」的 X　＋　語料挖出的動詞/形容詞。"""
    verbs = set()
    with open(data_txt, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#"):
                continue
            p = line.split()
            if len(p) < 3 or len(p[1]) != 2:
                continue
            if p[1].endswith("得") and p[0].endswith("ㄉㄜ˙"):
                verbs.add(p[1][0])
    return (verbs | MINED_HEADS) - FIXED_HEADS - NEVER_HEADS


def load_dict_verbs(data_txt=DATA_TXT):
    """只有詞庫「X得」詞條來的動詞。這份沒有雜訊，程度副詞那半用它。"""
    out = set()
    with open(data_txt, encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#"):
                continue
            p = line.split()
            if len(p) >= 3 and len(p[1]) == 2 and p[1].endswith("得") and p[0].endswith("ㄉㄜ˙"):
                out.add(p[1][0])
    return out - FIXED_HEADS - NEVER_HEADS


DICT_VERBS = None


def should_be_de2(sentence, idx, verbs, words=None):
    """這個位置該不該是「得」。回傳 (要不要改, 理由)。

    idx 指向句子裡那個 ㄉㄜ˙ 的位置。
    """
    if idx == 0 or idx + 1 >= len(sentence):
        return False, "在句首或句尾，沒有前後文"

    if idx >= 2 and sentence[idx - 2] in LEFT_DEGREE:
        return False, f"左邊已被「{sentence[idx - 2]}」修飾，這個的是「…的東西」"

    left = sentence[idx - 1]
    if left + sentence[idx] in NEVER_WORDS:
        return False, f"「{left + sentence[idx]}」是固定詞，不動"
    if left not in verbs:
        return False, f"左邊「{left}」不是動詞或形容詞"

    right1 = sentence[idx + 1]
    right2 = sentence[idx + 1:idx + 3]

    if right2 in NOUN2:
        return False, f"右邊「{right2}」是名詞"

    if right2 in NARROW_2:
        return True, f"{left} + 得 + {right2}"

    # 後面兩個字是詞庫裡的詞 → 名詞（極致／下場／出路／最後／動作／太妹），不要動。
    # 這道護欄拿掉的話，誤改率會從個位數跳到兩成以上（實測過）。
    # 純程度副詞也要過這關 —— 「太妹」就是這樣漏掉的。
    if words and right2 in words:
        return False, f"右邊「{right2}」是詞，當名詞看待"

    if right1 in RESULT:
        return True, f"{left} + 得 + {right1}"

    # 程度副詞那半誤判多，左邊只認詞庫確定的動詞（不收語料挖的形容詞）
    if right1 in DEGREE or right1 in PURE_DEGREE:
        global DICT_VERBS
        if DICT_VERBS is None:
            DICT_VERBS = load_dict_verbs()
        if left in DICT_VERBS:
            return True, f"{left}(詞庫動詞) + 得 + {right1}"
        return False, f"左邊「{left}」不是詞庫確認的動詞，程度副詞這半不冒險"

    return False, f"右邊「{right1}」不在安全清單裡"


def apply_rule(sentence, verbs, words=None):
    """把句子裡該改成「得」的位置改掉。回傳 (新句子, [改動說明])。"""
    chars = list(sentence)
    changes = []
    for i, ch in enumerate(chars):
        if ch not in "的得":
            continue
        hit, why = should_be_de2(sentence, i, verbs, words)
        if hit and ch == "的":
            chars[i] = "得"
            changes.append((i, "的→得", why))
    return "".join(chars), changes


